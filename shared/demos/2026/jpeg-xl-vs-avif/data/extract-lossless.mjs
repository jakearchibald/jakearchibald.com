// Creates a lossless chart module from several image-codec-bench results.json
// files, with the data trimmed down to what the charts need.
// Usage: node extract-lossless.mjs name.ts "Label=path/to/results.json" …
import { readFileSync, renameSync, writeFileSync } from 'fs';

const [outputPath, ...inputs] = process.argv.slice(2);

const images = inputs.map((input) => {
  const separator = input.indexOf('=');
  const label = input.slice(0, separator);
  const { lossless } = JSON.parse(
    readFileSync(input.slice(separator + 1), 'utf8'),
  );

  const rows = lossless
    .filter((row) => !row.skipped && !row.isSource)
    // jixel's speeds below its default (fast) aren't charted. Every encoder's
    // default is its fastest setting shown.
    .filter((row) => row.codec !== 'jixel' || row.effort >= 3)
    .map((row) => {
      if (!row.bitExact) throw Error(`${label} ${row.label} isn't lossless`);
      return {
        codec: row.codec,
        effort: row.effort,
        effortLabel: row.effortLabel,
        // Only jixel has a patches setting
        patches: row.patches ?? undefined,
        bytes: row.bytes,
        encodeMs: row.timings.multi.bestMs,
        encodeMemory: row.peakMemory.multi,
        decodeMs: Object.fromEntries(
          Object.entries(row.decode ?? {})
            .filter(([, result]) => result?.meanMs != null)
            .map(([browser, result]) => [browser, result.meanMs]),
        ),
      };
    });

  return { label, rows };
});

const output = `// Generated by extract-lossless.mjs
import { h, type FunctionalComponent } from 'preact';
import LosslessChart, {
  type LosslessChartProps,
  type LosslessImage,
} from '../LosslessChart';

const images: LosslessImage[] = ${JSON.stringify(images)};

const Chart: FunctionalComponent<LosslessChartProps> = (props) =>
  h(LosslessChart, { images, ...props });

export default Chart;
`;

// Written to a temporary file and renamed, so watchers never see a partially
// written file.
const tempPath = `${outputPath}.tmp`;
writeFileSync(tempPath, output);
renameSync(tempPath, outputPath);
