// Creates a chart module from an image-codec-bench JPEG transcode
// results.json, with the data trimmed down to what the charts need.
// Usage: node extract-transcode.mjs path/to/results.json name.ts
import { readFileSync, renameSync, writeFileSync } from 'fs';

const [resultsPath, outputPath] = process.argv.slice(2);

const { images } = JSON.parse(readFileSync(resultsPath, 'utf8'));

if (images.length !== 1) throw Error('Expected results for one image');

const decodeTimes = (decode = {}) =>
  Object.fromEntries(
    Object.entries(decode)
      .filter(([, result]) => result?.meanMs != null)
      .map(([browser, result]) => [browser, result.meanMs]),
  );

const rows = images[0].rows.map((row) => ({
  width: row.width,
  height: row.height,
  quality: row.quality,
  jpegBytes: row.jpeg.bytes,
  jxlBytes: row.jxl.bytes,
  jpegDecodeMs: decodeTimes(row.jpeg.decode),
  jxlDecodeMs: decodeTimes(row.jxl.decode),
}));

const output = `// Generated by extract-transcode.mjs
import { h, type FunctionalComponent } from 'preact';
import TranscodeChart, {
  type TranscodeChartProps,
  type TranscodeRow,
} from '../TranscodeChart';

const data: TranscodeRow[] = ${JSON.stringify(rows)};

const Chart: FunctionalComponent<TranscodeChartProps> = (props) =>
  h(TranscodeChart, { data, ...props });

export default Chart;
`;

// Written to a temporary file and renamed, so watchers never see a partially
// written file.
const tempPath = `${outputPath}.tmp`;
writeFileSync(tempPath, output);
renameSync(tempPath, outputPath);
