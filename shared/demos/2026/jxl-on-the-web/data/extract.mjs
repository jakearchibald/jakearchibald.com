// Creates a chart module from an image-codec-bench results.json, with the data
// trimmed down to what the charts need.
// Usage: node extract.mjs path/to/results.json name.ts
import { readFileSync, renameSync, writeFileSync } from 'fs';

const [resultsPath, outputPath] = process.argv.slice(2);

const { jobs } = JSON.parse(readFileSync(resultsPath, 'utf8'));

const rows = jobs
  .filter((job) => !job.lossless)
  .map((job) => ({
    seriesId: job.seriesId,
    codec: job.codec,
    effort: job.effort,
    effortLabel: job.effortLabel,
    yuv: job.yuv,
    hdrMode: job.hdrMode ?? null,
    quality: job.quality,
    bytes: job.bytes,
    ssimulacra2: job.score,
    jod: job.cvvdp?.jod ?? null,
    encodeMs: job.timings?.multi?.bestMs ?? null,
    encodeMemory: job.peakMemory?.multi ?? null,
    decodeMs: Object.fromEntries(
      Object.entries(job.decode ?? {})
        .filter(([, result]) => result?.meanMs != null)
        .map(([browser, result]) => [browser, result.meanMs]),
    ),
  }));

const output = `// Generated by extract.mjs
import { h, type FunctionalComponent } from 'preact';
import QualityChart, { type ChartProps, type Row } from '../QualityChart';

const data: Row[] = ${JSON.stringify(rows)};

const Chart: FunctionalComponent<ChartProps> = (props) =>
  h(QualityChart, { data, ...props });

export default Chart;
`;

// Written to a temporary file and renamed, so watchers never see a partially
// written file.
const tempPath = `${outputPath}.tmp`;
writeFileSync(tempPath, output);
renameSync(tempPath, outputPath);
